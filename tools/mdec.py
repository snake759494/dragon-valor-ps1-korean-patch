class BitReader:
    """16비트 LE 워드에서 MSB 우선으로 비트를 읽는다."""
    def __init__(self, data, start=0):
        self.d = data; self.pos = start; self.bit = 0

    def read(self, n):
        v = 0
        for _ in range(n):
            i = self.pos + (1 - (self.bit // 8))     # LE 워드 내 바이트 스왑
            if i >= len(self.d): raise EOFError
            b = (self.d[i] >> (7 - (self.bit % 8))) & 1
            v = (v << 1) | b
            self.bit += 1
            if self.bit == 16: self.bit = 0; self.pos += 2
        return v

    def peek_bits(self, n):
        sp, sb = self.pos, self.bit
        try: v = self.read(n)
        except EOFError: v = None
        self.pos, self.bit = sp, sb
        return v

    def tell(self):
        return self.pos * 8 + self.bit


class BitWriter:
    """비트를 정수 누산기에 모아 16비트 LE 워드로 낸다 (메모리 효율)."""
    def __init__(self):
        self.buf = bytearray()
        self.acc = 0
        self.n = 0

    def _push(self, bit):
        self.acc = (self.acc << 1) | bit
        self.n += 1
        if self.n == 16:
            self.buf += struct.pack('<H', self.acc)
            self.acc = 0; self.n = 0

    def write(self, s):
        for c in s: self._push(1 if c == '1' else 0)

    def write_num(self, v, n):
        for i in range(n - 1, -1, -1): self._push((v >> i) & 1)

    def nbits(self):
        return len(self.buf) * 8 + self.n

    def bytes(self):
        acc, n = self.acc, self.n
        out = bytearray(self.buf)
        if n:
            out += struct.pack('<H', acc << (16 - n))
        return bytes(out)


def decode_frame(bs, nblocks=None):
    """비트스트림 -> (헤ader, [블록...]).  블록 = dict(q, dc, ac=[(run,level)...])"""
    nwords, magic, qscale, ver = struct.unpack('<HHHH', bs[:8])
    assert magic == 0x3800, hex(magic)
    br = BitReader(bs, 8)
    blocks = []
    try:
        while True:
            if nblocks is not None and len(blocks) >= nblocks: break
            if br.pos >= len(bs): break
            dc = br.read(10)
            if dc >= 512: dc -= 1024
            ac = []
            while True:
                s = ''
                code = None
                for _ in range(16):
                    s += '1' if br.read(1) else '0'
                    if s == ESCAPE:
                        run = br.read(6)
                        lv = br.read(10)
                        if lv >= 512: lv -= 1024
                        code = ('esc', run, lv); break
                    if s in DEC:
                        code = DEC[s]; break
                if code is None:
                    raise ValueError('알 수 없는 VLC %r' % s)
                if code == 'EOB':
                    break
                if code[0] == 'esc':
                    ac.append((code[1], code[2], 1))     # 이스케이프로 부호화됨
                else:
                    run, lv = code
                    if br.read(1): lv = -lv
                    ac.append((run, lv, 0))
            blocks.append(dict(dc=dc, ac=ac))
    except EOFError:
        pass
    return dict(nwords=nwords, qscale=qscale, ver=ver), blocks


def encode_blocks(blocks, qscale, ver):
    bw = BitWriter()
    for b in blocks:
        bw.write_num(b['dc'] & 0x3FF, 10)
        for run, lv, esc in b['ac']:
            key = (run, abs(lv))
            if not esc and key in ENC:
                bw.write(ENC[key])
                bw.write('1' if lv < 0 else '0')
            else:
                bw.write(ESCAPE)
                bw.write_num(run, 6)
                bw.write_num(lv & 0x3FF, 10)
        bw.write(EOB)
    # 마지막 블록 EOB 뒤에는 반드시 10비트 프레임 종단 마커가 온다.
    # 원본은 24,301프레임 전부 이 마커로 끝난다. 없으면 게임의 VLC 디코더가
    # 프레임 끝을 못 찾고 뒤따르는 0 패딩을 계속 소비하면서 런레벨 코드를
    # 스테이징 버퍼 밖(=지도 지형 텍스처가 올라가는 VRAM)으로 써 나간다.
    bw.write(ENDMARK)
    body = bw.bytes()
    # 헤더 첫 필드는 바이트 수가 아니라 MDEC 코드 수 기반 값이다.
    #   코드 수 = 블록당 (DC 1 + AC n + EOB 1)
    #   nwords  = ceil(코드수/2) 를 32의 배수로 올림
    codes = sum(2 + len(b['ac']) for b in blocks)
    nwords = ((codes + 1) // 2 + 31) // 32 * 32
    # 프레임 전체 길이는 반드시 4바이트(32비트 DMA 워드) 배수여야 한다.
    # 원본은 예외 없이 이 규칙을 지킨다. 어기면 게임이 마지막 워드를 잘라 읽어
    # VLC 디코더가 버퍼를 넘어가고, 이웃 VRAM(지도 지형 텍스처)이 깨진다.
    if (8 + len(body)) % 4: body += bytes(4 - (8 + len(body)) % 4)
    return struct.pack('<HHHH', nwords, 0x3800, qscale, ver) + body
